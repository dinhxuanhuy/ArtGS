#!/usr/bin/env bash
# Build the NCKH-2027 Drive layout locally from the original archives, then upload it.
#   scripts/drive_publish_data.sh stage     # build downloads/nckh_staging (no network)
#   scripts/drive_publish_data.sh upload    # rclone copy -> nckh:  (remote root = NCKH-2027)
#   scripts/drive_publish_data.sh check     # rclone check local staging vs Drive
#   scripts/drive_publish_data.sh resources # (re)upload only resources/papers
# Extracted trees are re-extracted from the archives (not copied from data/, which
# training modifies), so Drive mirrors the archives exactly. Idempotent.
set -euo pipefail
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"; cd "$REPO"
ST="${STAGING:-$REPO/downloads/nckh_staging}"
REMOTE="${RCLONE_REMOTE:-nckh:}"
RAW="$REPO/data/_raw"
RC=(rclone --transfers 8 --checkers 16 --drive-chunk-size 64M --fast-list --stats 60s --stats-one-line --stats-log-level NOTICE)

stage() {
  local A="$ST/data/archives"
  mkdir -p "$A" "$ST/data/processed" "$ST/data/raw" "$ST/checkpoints" "$ST/_env_cache/wheels" "$ST/experiments"
  # hardlink archives under their manifest names (same filesystem -> no extra space)
  ln -f "$RAW/ArtGS-Multi/ArtGS_data.zip" "$A/ArtGS_data.zip"
  ln -f "$RAW/ArtGS-Multi/ArtGS_ckpt.zip" "$A/ArtGS_ckpt.zip"
  ln -f "$RAW/ArtGS-Multi/realscan.zip"   "$A/realscan.zip"
  ln -f "$RAW/PARIS/paris_dataset.zip"    "$A/PARIS_dataset.zip"
  ln -f "$RAW/DTA-Multi/multi_part.tar"   "$A/DTA_multi_part.tar"
  LD=(python3 scripts/load_data.py --downloads "$A")
  "${LD[@]}" paris dta artgs        --root "$ST/data/processed"   # verifies sha256 of every archive
  "${LD[@]}" paris_raw dta_raw realscan_raw --root "$ST/data/raw"
  "${LD[@]}" ckpt                   --root "$ST/checkpoints"
  rm -f "$A"/*.sha256 "$A"/*.part
  ( cd "$A" && python3 - <<'EOF'
import json; m = json.load(open("../../../../configs/datasets.json"))
with open("SHA256SUMS", "w") as f:
    for n, a in sorted(m["archives"].items()):
        f.write(f"{a['sha256']}  {n}\n")
EOF
  sha256sum -c --quiet SHA256SUMS && echo "[stage] SHA256SUMS ok" )
  stage_resources
  write_readmes
  echo "[stage] done: $ST"; du -sh "$ST"/* | sed 's|'"$ST"'/||'
}

stage_resources() {  # related-work papers (PDF + text extract + overview README); notes stay local
  local R="$ST/resources/papers"; mkdir -p "$R"
  [ -d paper_resource ] || { echo "[stage] no paper_resource/, skipping resources"; return; }
  for d in paper_resource/*/; do rsync -a "$d" "$R/$(basename "$d")/"; done
  cp paper_resource/README.md "$R/README.md"
}

count() { find "$1" -type f ! -name '.artgs_complete.json' | wc -l; }
size()  { du -sh --apparent-size "$1" | cut -f1; }

write_readmes() {
  local P="$ST/data/processed" R="$ST/data/raw" C="$ST/checkpoints/ArtGS_ckpt"
  cat > "$ST/README.md" <<EOF
# NCKH-2027: ArtGS research storage

Persistent storage for the ArtGS research repo (https://github.com/dinhxuanhuy/ArtGS).
Training never reads from Drive directly: each Colab session copies what it needs to local disk.

| Folder | Contents |
|---|---|
| \`data/archives/\` | Original archives + \`SHA256SUMS\`. Source of truth; \`scripts/load_data.py\` reads these. |
| \`data/processed/\` | Ready-to-train data, layout \`<dataset>/<subset>/<scene>\` (\`--dataset/--subset/--scene_name\`). |
| \`data/raw/\` | Original, unconverted datasets (for re-processing). |
| \`checkpoints/ArtGS_ckpt/\` | Official ArtGS checkpoints from the paper authors. |
| \`_env_cache/\` | Built CUDA-extension wheels, keyed \`py-torch-cuda-sm-srchash\`. Managed by scripts; do not edit. |
| \`experiments/\` | Results and checkpoints from our own runs. |
| \`resources/papers/\` | Related papers (ArtGS, REArtGS, REArtGS++, Rest2Art): PDF + text extract + overview README. |

Generated by \`scripts/drive_publish_data.sh\` on $(date -u +%F).
EOF
  cat > "$ST/data/README.md" <<EOF
# data/

## archives/ (verify with \`sha256sum -c SHA256SUMS\`)
| File | Size | Source | Extracted to |
|---|---|---|---|
| \`ArtGS_data.zip\` | 2.97 GB | HF \`YuLiu/ArtGS-Dataset\` | \`processed/{paris,dta,artgs}\` |
| \`ArtGS_ckpt.zip\` | 0.93 GB | HF \`YuLiu/ArtGS-Dataset\` | \`../checkpoints/ArtGS_ckpt\` |
| \`realscan.zip\` | 2.13 GB | HF \`YuLiu/ArtGS-Dataset\` | \`raw/ArtGS-realscan\` |
| \`PARIS_dataset.zip\` | 2.24 GB | aspis.cmpt.sfu.ca/projects/paris (\`dataset.zip\`) | \`raw/PARIS\` |
| \`DTA_multi_part.tar\` | 0.12 GB | NVlabs/DigitalTwinArt Google Drive (\`multi_part.tar\`) | \`raw/DTA-Multi\` |

## processed/ (converted by the ArtGS authors; what training uses)
| Path | Scenes | Files | Size | Flags |
|---|---|---|---|---|
| \`paris/sapien/\` | $(ls "$P/paris/sapien" | wc -l) | $(count "$P/paris/sapien") | $(size "$P/paris/sapien") | \`--dataset paris --subset sapien\` |
| \`paris/realscan/\` | $(ls "$P/paris/realscan" | wc -l) | $(count "$P/paris/realscan") | $(size "$P/paris/realscan") | \`--dataset paris --subset realscan\` |
| \`dta/sapien/\` | $(ls "$P/dta/sapien" | wc -l) | $(count "$P/dta/sapien") | $(size "$P/dta/sapien") | \`--dataset dta --subset sapien\` |
| \`artgs/sapien/\` | $(ls "$P/artgs/sapien" | wc -l) | $(count "$P/artgs/sapien") | $(size "$P/artgs/sapien") | \`--dataset artgs --subset sapien\` |

Scenes:
- PARIS sapien: $(ls "$P/paris/sapien" | paste -sd, | sed 's/,/, /g')
- PARIS realscan: $(ls "$P/paris/realscan" | paste -sd, | sed 's/,/, /g')
- DTA: $(ls "$P/dta/sapien" | paste -sd, | sed 's/,/, /g')
- ArtGS: $(ls "$P/artgs/sapien" | paste -sd, | sed 's/,/, /g')

Each scene: \`transforms_{train,test}_{start,end}.json\`, \`{start,end}/{train,test}/{rgba,depth}/*.png\`
(depth: 16-bit PNG, mm), \`gt/\` (trans.json, axis meshes) for evaluation.

## raw/ (original releases, unconverted)
| Path | Files | Size | Contents |
|---|---|---|---|
| \`PARIS/\` | $(count "$R/PARIS") | $(size "$R/PARIS") | \`load/\` (renders + cameras), \`data/\` (meshes) for sapien + realscan |
| \`DTA-Multi/\` | $(count "$R/DTA-Multi") | $(size "$R/DTA-Multi") | $(ls "$R/DTA-Multi" | paste -sd, | sed 's/,/, /g') |
| \`ArtGS-realscan/\` | $(count "$R/ArtGS-realscan") | $(size "$R/ArtGS-realscan") | iPad scans: $(ls "$R/ArtGS-realscan" | paste -sd, | sed 's/,/, /g') |

## checkpoints (../checkpoints/ArtGS_ckpt)
$(count "$C") files, $(size "$C"). Layout \`<dataset>/<scene>/{cfg_args, deform/, point_cloud/}\`;
use as \`--model_path\` with \`render.py --iteration best\`.
EOF
  printf '# experiments/\n\nOne folder per run: `<YYYYMMDD>_<name>_<gitsha>/` (config, metrics.json, logs, checkpoints).\n' > "$ST/experiments/README.md"
  printf '# _env_cache/\n\nManaged by scripts/bootstrap_colab.sh. Delete a key folder to force a rebuild.\n' > "$ST/_env_cache/README.md"
}

need_remote() {
  rclone listremotes 2>/dev/null | grep -qx "${REMOTE%%:*}:" || {
    echo "rclone remote '${REMOTE}' not configured. Run once (interactive):"
    echo "  rclone config create nckh drive scope=drive root_folder_id=<NCKH-2027 folder ID>"
    exit 1; }
}

case "${1:-}" in
  stage)  stage ;;
  resources) need_remote; stage_resources; "${RC[@]}" copy "$ST/resources" "${REMOTE}resources" ;;
  upload) need_remote; [ -f "$ST/README.md" ] || stage
          rclone about "$REMOTE" 2>/dev/null || true
          "${RC[@]}" copy "$ST" "$REMOTE" --exclude '_env_cache/wheels/**' ;;
  check)  need_remote; "${RC[@]}" check "$ST" "$REMOTE" --one-way --exclude '_env_cache/wheels/**' ;;
  *) sed -n 2,7p "$0"; exit 2 ;;
esac
