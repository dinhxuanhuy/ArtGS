#!/usr/bin/env python3
"""Aggregate runs/*/metrics.json into results/leaderboard.md (+ results/leaderboard.csv).

    python scripts/leaderboard.py [--runs runs] [--out results]

Baseline = results from the official ArtGS checkpoints re-evaluated in OUR environment
(model == "official"; produced by scripts/jobs/eval_official.sh). Each of our results is
shown next to the baseline for the same dataset/scene, with the delta. Only split=train
(the geometry/joint eval that render.py runs with --skip_test) is tabulated.
"""
import argparse, csv, json
from pathlib import Path

KEYS = ["avg_angle", "avg_distance", "avg_theta_diff", "avg_CD_static", "avg_CD_dynamic", "avg_CD_whole"]
SHORT = {"avg_angle": "axis ang", "avg_distance": "axis pos", "avg_theta_diff": "part motion",
         "avg_CD_static": "CD static", "avg_CD_dynamic": "CD dyn", "avg_CD_whole": "CD whole"}


def fmt(x):
    return "" if x is None else (f"{x:.4f}" if abs(x) < 100 else f"{x:.1f}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", type=Path, default=Path("runs"))
    ap.add_argument("--out", type=Path, default=Path("results"))
    a = ap.parse_args()
    rows = []
    for mj in sorted(a.runs.glob("*/metrics.json")):
        d = json.loads(mj.read_text())
        for r in d["results"]:
            if r.get("split") != "train" or "dataset" not in r:
                continue
            rows.append({"run_id": d["run_id"], "exit": d.get("exit_code"), **{k: r.get(k) for k in
                         ("dataset", "subset", "scene", "model", "iteration")},
                         **{k: r["metrics"].get(k) for k in KEYS}})
    a.out.mkdir(parents=True, exist_ok=True)
    with open(a.out / "leaderboard.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["run_id", "exit", "dataset", "subset", "scene", "model", "iteration", *KEYS])
        w.writeheader(); w.writerows(rows)

    base = {}
    for r in rows:
        if r["model"] == "official":
            base[(r["dataset"], r["scene"])] = r   # latest official eval wins
    lines = ["# Leaderboard", "",
             "Generated by `scripts/leaderboard.py`. Lower is better for all columns. "
             "Baseline = official ArtGS checkpoints re-evaluated in this environment; "
             "values in parentheses are deltas vs baseline (negative = better).", ""]
    for key in sorted({(r["dataset"], r["scene"]) for r in rows}):
        lines += [f"## {key[0]} / {key[1]}", "",
                  "| run | model | iter | " + " | ".join(SHORT[k] for k in KEYS) + " |",
                  "|---|---|---|" + "---|" * len(KEYS)]
        b = base.get(key)
        group = sorted((r for r in rows if (r["dataset"], r["scene"]) == key), key=lambda r: (r["model"] != "official", r["run_id"]))
        for r in group:
            cells = []
            for k in KEYS:
                v = r[k]
                if b is not None and r is not b and v is not None and b[k] is not None:
                    cells.append(f"{fmt(v)} ({v - b[k]:+.4f})")
                else:
                    cells.append(fmt(v))
            lines.append(f"| `{r['run_id']}` | {r['model']} | {r['iteration']} | " + " | ".join(cells) + " |")
        lines.append("")
    if not rows:
        lines.append("_No results yet._")
    (a.out / "leaderboard.md").write_text("\n".join(lines) + "\n")
    print(f"{len(rows)} results, {len(base)} baselines -> {a.out}/leaderboard.md")


if __name__ == "__main__":
    main()
